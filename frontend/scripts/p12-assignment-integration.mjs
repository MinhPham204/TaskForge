import assert from 'node:assert/strict';
import { taskEditorDraft, saveTaskEditor, planTaskEditorSave, editorPermissions } from '../src/utils/taskEditor.js';
import { getTaskEditorAccess } from '../src/utils/taskCapabilities.js';
import { requireEligibleNewAssignees } from '../src/utils/taskAssignments.js';
let input = '';
for await (const chunk of process.stdin) input += chunk;
const f = JSON.parse(input);
assert.match(f.baseURL, /^http:\/\/127\.0\.0\.1:\d+$/);
const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, String(value)), removeItem: key => values.delete(key) };
globalThis.window = { location: { href: '' } };
const { store } = await import('../src/store/index.js');
const { setCredentials } = await import('../src/store/authSlice.js');
const { default: client } = await import('../src/utils/axiosInstance.js');
const { taskApi } = await import('../src/services/taskApi.js');
const { projectApi } = await import('../src/services/projectApi.js');
const { dashboardApi } = await import('../src/services/dashboardApi.js');
const { collaborationApi } = await import('../src/services/collaborationApi.js');
client.defaults.baseURL = f.baseURL;
const login = (id, accessToken) => { store.dispatch(setCredentials({ user: { id }, accessToken })); localStorage.setItem('activeOrganizationId', f.organizationId); };
const invoke = async (api, name, args) => store.dispatch(api.endpoints[name].initiate(args, { subscribe: false, forceRefetch: true })).unwrap();
const { projectId, taskId } = f;
const readDetail = id => invoke(taskApi, 'getProjectTaskDetail', { projectId, taskId: id });
try {
  login(f.pmUserId, f.pmAccessToken);
  const project = await invoke(projectApi, 'getProjectById', projectId);
  const members = await invoke(projectApi, 'getProjectMembers', projectId);
  const candidates = await invoke(taskApi, 'getTaskAssignmentCandidates', { projectId, teamId: f.teamId });
  for (const member of candidates) assert.ok(members.some(projectMember => projectMember.projectMembershipId === member.projectMembershipId));
  assert.ok(candidates.some(member => member.projectMembershipId === f.secondAssigneeId));
  const original = await readDetail(taskId);
  const session = { task: original, initial: taskEditorDraft(original) };
  const draft = { ...taskEditorDraft(original), assigneeIds: [...original.assigneeProjectMembershipIds, f.secondAssigneeId] };
  const calls = [];
  const execute = async (name, args) => { calls.push(name); return invoke(taskApi, name, args); };
  requireEligibleNewAssignees(original.assigneeProjectMembershipIds, draft.assigneeIds, candidates);
  assert.equal((await saveTaskEditor({ session, draft, projectId, project, members, execute, readDetail })).complete, true);
  assert.deepEqual(new Set((await readDetail(taskId)).assigneeProjectMembershipIds), new Set(draft.assigneeIds));
  draft.assigneeIds = [...original.assigneeProjectMembershipIds];
  assert.equal((await saveTaskEditor({ session, draft, projectId, project, members, execute, readDetail })).complete, true);
  assert.deepEqual(calls, ['assignTask', 'unassignTask']);
  assert.deepEqual((await readDetail(taskId)).assigneeProjectMembershipIds, original.assigneeProjectMembershipIds);
  // The actual MyTasks response supplies the same identity to the shared editor.
  login(f.assigneeUserId, f.assigneeAccessToken);
  const mine = await invoke(taskApi, 'getMyTasks', {});
  const selected = mine.find(task => task.id === taskId);
  assert.equal(selected.projectId, projectId);
  assert.equal(getTaskEditorAccess(selected).allowed, true);
  const full = await readDetail(selected.id);
  const contributorProject = await invoke(projectApi, 'getProjectById', projectId);
  const access = editorPermissions(full, contributorProject);
  assert.equal(access.editContent.allowed, true); assert.equal(access.assign.allowed, false);
  assert.equal(editorPermissions(null, contributorProject).configureApproval.allowed, false);
  const editSession = { task: full, initial: taskEditorDraft(full) };
  const editDraft = { ...taskEditorDraft(full), title: 'P12 MyTasks assignee edit' };
  assert.equal((await saveTaskEditor({ session: editSession, draft: editDraft, projectId, project: contributorProject, members, execute, readDetail })).complete, true);
  assert.equal((await readDetail(taskId)).title, editDraft.title);
  assert.throws(() => planTaskEditorSave(editSession, { ...editDraft, assigneeIds: [...editDraft.assigneeIds, f.secondAssigneeId] }, { project: contributorProject, members }), /Project Manager/);
  console.log('P12 actual frontend assignment/MyTasks editor HTTP acceptance passed (candidates, multiple add/remove, assignee content edit, Contributor management gates)');
} catch (error) {
  console.error(`P12 assignment consumer failed: ${error instanceof assert.AssertionError ? error.message : 'HTTP/runtime failure'}; status=${error.status || 'n/a'}`);
  process.exitCode = 1;
} finally { for (const api of [taskApi, projectApi, collaborationApi, dashboardApi]) store.dispatch(api.util.resetApiState()); }
